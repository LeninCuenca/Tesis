CREATE TABLE IF NOT EXISTS centrales (
    central_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE,
    ubicacion VARCHAR(200),
    potencia_instalada_kw NUMERIC(12, 3),
    activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS equipos (
    equipo_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    central_id SMALLINT NOT NULL REFERENCES centrales (central_id),
    tipo VARCHAR(40) NOT NULL,
    fabricante VARCHAR(80),
    modelo VARCHAR(120),
    identificador VARCHAR(120),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS ix_equipos_central ON equipos (central_id);

CREATE TABLE IF NOT EXISTS variables_catalogo (
    variable_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(80) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('electrica', 'ambiental', 'energetica', 'demanda')),
    unidad VARCHAR(20),
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS mediciones_energeticas (
    central_id SMALLINT NOT NULL REFERENCES centrales (central_id),
    fecha_hora TIMESTAMPTZ NOT NULL,
    corriente_ca_l1 NUMERIC(14, 4), corriente_ca_l2 NUMERIC(14, 4), corriente_ca_l3 NUMERIC(14, 4),
    corriente_cc_mpp1 NUMERIC(14, 4), corriente_cc_mpp2 NUMERIC(14, 4),
    energia NUMERIC(16, 4), energia_mpp1 NUMERIC(16, 4), energia_mpp2 NUMERIC(16, 4),
    factor_potencia NUMERIC(10, 6), potencia_aparente NUMERIC(16, 4), potencia_reactiva NUMERIC(16, 4),
    rendimiento_especifico NUMERIC(16, 6),
    tension_ca_l1 NUMERIC(14, 4), tension_ca_l2 NUMERIC(14, 4), tension_ca_l3 NUMERIC(14, 4),
    tension_cc_mpp1 NUMERIC(14, 4), tension_cc_mpp2 NUMERIC(14, 4),
    consumido_directamente NUMERIC(16, 4), consumo NUMERIC(16, 4),
    energia_obtenida_red NUMERIC(16, 4), energia_suministrada_red NUMERIC(16, 4),
    produccion_fotovoltaica NUMERIC(16, 4),
    potencia_aparente_l1_alimentacion NUMERIC(16, 4), potencia_aparente_l2_alimentacion NUMERIC(16, 4), potencia_aparente_l3_alimentacion NUMERIC(16, 4),
    potencia_efectiva_l1_alimentacion NUMERIC(16, 4), potencia_efectiva_l2_alimentacion NUMERIC(16, 4), potencia_efectiva_l3_alimentacion NUMERIC(16, 4),
    tension_ca_l1_alimentacion NUMERIC(14, 4), tension_ca_l2_alimentacion NUMERIC(14, 4), tension_ca_l3_alimentacion NUMERIC(14, 4),
    irradiacion NUMERIC(14, 4), temperatura_ambiente NUMERIC(10, 4), temperatura_modulo NUMERIC(10, 4),
    PRIMARY KEY (central_id, fecha_hora)
);

CREATE INDEX IF NOT EXISTS ix_mediciones_fecha ON mediciones_energeticas (fecha_hora);
CREATE INDEX IF NOT EXISTS ix_mediciones_produccion ON mediciones_energeticas (central_id, fecha_hora, produccion_fotovoltaica);

CREATE TABLE IF NOT EXISTS resumen_diario (
    central_id SMALLINT NOT NULL REFERENCES centrales (central_id),
    fecha DATE NOT NULL,
    produccion_fotovoltaica_wh NUMERIC(18, 4),
    consumo_wh NUMERIC(18, 4),
    energia_red_wh NUMERIC(18, 4),
    potencia_maxima NUMERIC(16, 4),
    irradiacion_promedio NUMERIC(14, 4),
    temperatura_promedio NUMERIC(10, 4),
    registros_validos INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (central_id, fecha)
);

CREATE INDEX IF NOT EXISTS ix_resumen_fecha ON resumen_diario (fecha);

